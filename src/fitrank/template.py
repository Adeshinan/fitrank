"""Write a commented starter config, for ``fitrank init``.

The generated file always passes ``fitrank validate`` once ``data.path`` and
``data.target`` point to real data without text or missing values. Preprocessing
is only suggested, commented out: it is applied once the user uncomments it.
"""

from pathlib import Path
from typing import Any

import pandas as pd
import yaml

from fitrank.data import is_text
from fitrank.evaluation import DEFAULT_PRIMARY, DEFAULT_SECONDARY
from fitrank.registry import Task, list_models

# A few fast models per task, each searched with its small default grid.
STARTER_MODELS: dict[Task, list[str]] = {
    "classification": ["logistic_regression", "knn", "decision_tree", "random_forest"],
    "regression": ["linear_regression", "ridge", "decision_tree", "random_forest"],
}

_COMMENT_COLUMN = 29  # comments line up, as in examples/iris.yaml


def render_config(
    task: Task,
    data_path: Path | None = None,
    target: str | None = None,
    frame: pd.DataFrame | None = None,
) -> str:
    """Return the text of a starter config for ``task``.

    ``frame`` is the data read from ``data_path``: its columns fill
    ``data.features`` and the suggested preprocessing groups.
    """
    path = data_path.as_posix() if data_path else "data.csv"
    project = data_path.stem if data_path else "my_project"
    features: Any = "all"
    if frame is not None and target is not None:
        features = [str(column) for column in frame.columns if column != target]
    models = STARTER_MODELS[task]
    others = [name for name in list_models(task) if name not in models]
    lines = [
        "# FitRank config generated by `fitrank init`. Next steps:",
        "#   fitrank validate <this file>   # check the config and the data (instant)",
        "#   fitrank run <this file>        # train, compare and rank the models",
        '# Keys marked "optional" can be removed: FitRank then uses the value shown.',
        "# Every key is explained in"
        " https://github.com/Adeshinan/fitrank/blob/main/examples/iris.yaml",
        "",
        "project:",
        _line(f"  name: {_flow(project)}", "names the results folder: runs/<name>_<date>_<time>/"),
        _line("  output_dir: runs", "optional: where results folders are created"),
        _line("  random_state: 42", "optional: same number = same split, same folds, same results"),
        _line("  n_jobs: 1", "optional: CPU cores for the search; -1 = all of them"),
        "",
        "data:",
        _line(
            f"  path: {_flow(path)}",
            "CSV, Excel (.xlsx) or Parquet; relative to the current folder",
        ),
        _line(
            f"  target: {_flow(target or 'target')}",
            "the column to predict" if target else "CHANGE ME: the column to predict",
        ),
        _line(f"  features: {_flow(features)}", 'optional: "all" other columns, or a list'),
    ]
    if features == "all":
        lines.append(
            "  # exclude: [id, name]      # optional, with features: all: columns to leave out"
        )
    if frame is not None and target is None:
        lines.append(f"  # columns of {path}: {_flow([str(c) for c in frame.columns])}")
    lines += [
        "",
        _line(
            f"task: {task}",
            "classification (predict a category) or regression (predict a number)",
        ),
        "",
        "# Preprocessing is explicit: FitRank changes nothing unless it is declared.",
        "# Each group applies its steps, in order, to its columns; other columns pass",
        "# through unchanged. Steps: scaler (also scaler: minmax, scaler: robust),",
        "# imputer (fill missing values), encoder (turn text categories into numbers).",
        "# Suggested groups: uncomment them (remove the leading '# ') to apply them.",
        *_preprocessing(frame, target),
        "",
        "# Each reduction is combined with each model: 1 reduction x"
        f" {len(models)} models = {len(models)} candidates.",
        "reduction:",
        _line("  - none", "the columns as they are; also pca: {n_components: [2, 5]}"),
        "",
        f"# Models by name: `fitrank list models --task {task}` shows them all.",
        "# Without params, a small default grid is searched; params: {name: [values]}",
        "# replaces it. Other scikit-learn models are given by their class path:",
        "#   - class: sklearn.ensemble.ExtraTreesClassifier",
        "models:",
        *(f"  - name: {name}" for name in models),
    ]
    if others:
        lines.append(f"  # also available: {', '.join(others)}")
    lines += [
        "",
        "evaluation:",
        _line("  test_size: 0.2", "optional: share of the rows kept aside for the test score"),
        _line("  cv: 5", "optional: number of cross-validation folds on the other rows"),
        _line("  search: grid", "optional: grid (every combination) or random (n_iter of them)"),
        _line(f"  primary_metric: {DEFAULT_PRIMARY[task]}", "optional: ranks the models"),
        _line(f"  metrics: {_flow(DEFAULT_SECONDARY[task])}", "optional: also on the test set"),
        "",
        "output:",
        _line(
            "  formats: [csv, json, markdown]", "optional: leaderboard files in the results folder"
        ),
        _line("  save_best_model: true", "optional: best_model.joblib, for `fitrank predict`"),
    ]
    return "\n".join(lines) + "\n"


def _preprocessing(frame: pd.DataFrame | None, target: str | None) -> list[str]:
    """The suggested groups, commented out: by column type when the data is known."""
    if frame is None:
        groups = {
            "numeric": (["column_a", "column_b"], ["scaler"]),
            "categorical": (["column_c"], ["encoder"]),
        }
    else:
        X = frame.drop(columns=[target]) if target in frame.columns else frame
        numeric = [column for column in X.columns if not is_text(X[column])]
        text = [column for column in X.columns if is_text(X[column])]
        groups = {}
        if numeric:
            steps: list[Any] = ["scaler"]
            if X[numeric].isna().any().any():
                steps.insert(0, {"imputer": {"strategy": "median"}})
            groups["numeric"] = ([str(c) for c in numeric], steps)
        if text:
            steps = ["encoder"]
            if X[text].isna().any().any():
                steps.insert(0, {"imputer": {"strategy": "most_frequent"}})
            groups["categorical"] = ([str(c) for c in text], steps)

    lines = ["# preprocessing:"]
    for name, (columns, steps) in groups.items():
        lines += [
            f"#   {name}:",
            f"#     columns: {_flow(columns)}",
            f"#     steps: {_flow(steps)}",
        ]
    return lines


def _line(text: str, comment: str) -> str:
    """``text`` with its comment aligned on the right, or above when ``text`` is too long."""
    if len(text) < _COMMENT_COLUMN - 1:
        return f"{text:<{_COMMENT_COLUMN - 1}} # {comment}"
    indent = text[: len(text) - len(text.lstrip())]
    return f"{indent}# {comment}\n{text}"


def _flow(value: Any) -> str:
    """``value`` as inline YAML, quoted only when needed: ``[a, 'yes', 'x: y']``."""
    text = yaml.safe_dump(value, default_flow_style=True, width=float("inf"), allow_unicode=True)
    return text.removesuffix("\n...\n").strip()
